const strip = (s: string) => s.replace(/[+#]/g, '');
const PARSED = NAMED_LINES.map(([name, line]) => ({ name, moves: line.split(' ').map(strip) }));

/** The opening name that fits the start of `sanMoves` best: the line that matches the most plies; when two match equally, the one listed first (the main line) wins. */
export function namedOpening(sanMoves: string[]): string | null {
  const mine = sanMoves.map(strip);
  let best: { name: string; n: number } | null = null;
  for (const o of PARSED) {
    let n = 0;
    while (n < o.moves.length && n < mine.length && o.moves[n] === mine[n]) n++;
    const full = n === o.moves.length;
    if ((full || n >= Math.min(o.moves.length, 6)) && (!best || n > best.n)) best = { name: o.name, n };
  }
  return best?.name ?? null;
}
/** Is this game still inside some known line (so the last move is a "book" move)? */
export function inBook(sanMoves: string[]): boolean {
  const mine = sanMoves.map(strip);
  if (!mine.length) return true;
  return PARSED.some((o) => o.moves.length >= mine.length && mine.every((m, i) => o.moves[i] === m));
}
/** All the named lines as move arrays (for the bots' book). */
export const NAMED_MOVES: string[][] = PARSED.map((p) => p.moves);
